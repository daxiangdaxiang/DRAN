    --sync_amm_reference_after_local_gradient_correction "${SYNC_AMM_REFERENCE_AFTER_LOCAL_GRADIENT_CORRECTION}"
    --global_gradient_correction "${GLOBAL_GRADIENT_CORRECTION}"
    --global_gradient_correction_step "${GLOBAL_GRADIENT_CORRECTION_STEP}"
    --reset_local_history_after_global_correction "${RESET_LOCAL_HISTORY_AFTER_GLOBAL_CORRECTION}"
    --sync_amm_reference_after_global_correction "${SYNC_AMM_REFERENCE_AFTER_GLOBAL_CORRECTION}"
    --amm_eta0 "${AMM_ETA0}"
    --amm_eta1 "${AMM_ETA1}"
    --amm_psi "${AMM_PSI}"
    --amm_phi "${AMM_PHI}"
    --amm_gamma_scale "${AMM_GAMMA_SCALE}"
    --amm_accepted_delta "${AMM_ACCEPTED_DELTA}"
    --amm_oscillation_count_period "${AMM_OSCILLATION_COUNT_PERIOD}"
    --amm_max_oscillations "${AMM_MAX_OSCILLATIONS}"
    --amm_proximal_start "${AMM_PROXIMAL_START}"
    --amm_dpgo_restart_fallback "${AMM_DPGO_RESTART_FALLBACK}"
    --amm_dpgo_surrogate_parity "${AMM_DPGO_SURROGATE_PARITY}"
    --amm_baseline_surrogate_state "${AMM_BASELINE_SURROGATE_STATE}"
    --amm_dpgo_recursive_simple_state "${AMM_DPGO_RECURSIVE_SIMPLE_STATE}"
    --amm_recursive_simple_reanchor_period "${AMM_RECURSIVE_SIMPLE_REANCHOR_PERIOD}"
    --amm_dpgo_strict_refined_gate "${AMM_DPGO_STRICT_REFINED_GATE}"
    --amm_dpgo_recover_translations_after_proximal "${AMM_DPGO_RECOVER_TRANSLATIONS_AFTER_PROXIMAL}"
    --amm_dpgo_refined_starts_at_recovered_proximal "${AMM_DPGO_REFINED_STARTS_AT_RECOVERED_PROXIMAL}"
    --amm_dpgo_mixed_surrogate_portfolio "${AMM_DPGO_MIXED_SURROGATE_PORTFOLIO}"
    --amm_mixed_surrogate_skip_simple_after_true_local_streak "${AMM_MIXED_SURROGATE_SKIP_SIMPLE_AFTER_TRUE_LOCAL_STREAK}"
    --amm_mixed_surrogate_force_simple_every_skipped_rounds "${AMM_MIXED_SURROGATE_FORCE_SIMPLE_EVERY_SKIPPED_ROUNDS}"
    --amm_cooldown_after_rejected "${AMM_COOLDOWN_AFTER_REJECTED}"
    --amm_prox_reset_skip_refined_solve "${AMM_PROX_RESET_SKIP_REFINED_SOLVE}"
    --amm_dpgo_proximal_fallback_only "${AMM_DPGO_PROXIMAL_FALLBACK_ONLY}"
    --amm_lazy_plain_after_certificate "${AMM_LAZY_PLAIN_AFTER_CERTIFICATE}"
    --amm_surrogate_first_exact_evaluation "${AMM_SURROGATE_FIRST_EXACT_EVALUATION}"
    --amm_max_soft_restart_hits0 "${AMM_MAX_SOFT_RESTART_HITS0}"
    --amm_max_soft_restart_hits1 "${AMM_MAX_SOFT_RESTART_HITS1}"
    --amm_local_merit_filter "${AMM_LOCAL_MERIT_FILTER}"
    --amm_local_merit_cost_tie_tolerance "${AMM_LOCAL_MERIT_COST_TIE_TOLERANCE}"
    --trace_amm "${TRACE_AMM}"
    --profile_optimizer "${PROFILE_OPTIMIZER}"
    --candidate_evaluation_cache "${CANDIDATE_EVALUATION_CACHE}"
    --candidate_object_reuse "${CANDIDATE_OBJECT_REUSE}"
    --reduced_adaptive_portfolio_certified_fast_path "${REDUCED_ADAPTIVE_PORTFOLIO_CERTIFIED_FAST_PATH}"
    --reduced_rotation_direct_objective "${REDUCED_ROTATION_DIRECT_OBJECTIVE}"
    --fused_candidate_evaluation "${FUSED_CANDIDATE_EVALUATION}"
    --lazy_candidate_gradient_evaluation "${LAZY_CANDIDATE_GRADIENT_EVALUATION}"
    --lazy_solver_start_gradient_evaluation "${LAZY_SOLVER_START_GRADIENT_EVALUATION}"
    --lazy_surrogate_candidate_gradient_evaluation "${LAZY_SURROGATE_CANDIDATE_GRADIENT_EVALUATION}"
    --reduced_rotation_curvature_cauchy_candidate "${REDUCED_ROTATION_CURVATURE_CAUCHY_CANDIDATE}"
    --reduced_rotation_curvature_fallback_candidate "${REDUCED_ROTATION_CURVATURE_FALLBACK_CANDIDATE}"
    --reduced_rotation_gradient_boundary_candidate "${REDUCED_ROTATION_GRADIENT_BOUNDARY_CANDIDATE}"
    --reduced_rotation_surrogate_tcg_accept "${REDUCED_ROTATION_SURROGATE_TCG_ACCEPT}"
    --reduced_rotation_skip_redundant_candidate_projection "${REDUCED_ROTATION_SKIP_REDUNDANT_CANDIDATE_PROJECTION}"
    --print_iteration_summary "${PRINT_ITERATION_SUMMARY}"
    --output_dir "${run_dir}"
    --save_iteration_estimates "${SAVE_ITERATION_ESTIMATES}"
    --save "${SAVE}"
  )
  if [[ -n "${external_initial_estimate_path}" ]]; then
    cmd+=(--external_initial_estimate "${external_initial_estimate_path}")
  fi
  if [[ -n "${LOCAL_STATE_EXTRAPOLATION_GAMMAS}" ]]; then
    cmd+=(--local_state_extrapolation_gammas "${LOCAL_STATE_EXTRAPOLATION_GAMMAS}")
  fi
  if [[ -n "${LOCAL_BOUNDARY_PROXIMAL_WEIGHTS}" ]]; then
    cmd+=(--local_boundary_proximal_weights "${LOCAL_BOUNDARY_PROXIMAL_WEIGHTS}")
  fi
  if [[ -n "${LOCAL_MODEL_G_EXTRAPOLATION_GAMMAS}" ]]; then
    cmd+=(--local_model_g_extrapolation_gammas "${LOCAL_MODEL_G_EXTRAPOLATION_GAMMAS}")
  fi
  if [[ -n "${COUPLED_STATE_G_EXTRAPOLATION_GAMMAS}" ]]; then
    cmd+=(--coupled_state_g_extrapolation_gammas "${COUPLED_STATE_G_EXTRAPOLATION_GAMMAS}")
  fi
  if [[ -n "${GLOBAL_STATE_EXTRAPOLATION_GAMMAS}" ]]; then
    cmd+=(--global_state_extrapolation_gammas "${GLOBAL_STATE_EXTRAPOLATION_GAMMAS}")
  fi
  if [[ -n "${LOCAL_GRADIENT_CORRECTION_STEPS}" ]]; then
    cmd+=(--local_gradient_correction_steps "${LOCAL_GRADIENT_CORRECTION_STEPS}")
  fi
  if [[ -n "${GLOBAL_GRADIENT_CORRECTION_STEPS}" ]]; then
    cmd+=(--global_gradient_correction_steps "${GLOBAL_GRADIENT_CORRECTION_STEPS}")
  fi
  if [[ -n "${AMM_GAMMA_SCALES}" ]]; then
    cmd+=(--amm_gamma_scales "${AMM_GAMMA_SCALES}")
  fi

  if [[ "${IS_DRY_RUN}" == "true" ]]; then
    printf 'DRY_RUN=1 DRAN_REDUCED_ROTATION_PACKED_CHOLESKY_PROJECT=%q DRAN_REDUCED_ROTATION_PACKED_TCG=%q DRAN_REDUCED_ROTATION_PACKED_RIEMANNIAN_HVP=%q DRAN_REDUCED_ROTATION_COMPACT_HVP=%q DRAN_REDUCED_ROTATION_PRECOMPUTED_RESPONSE_HVP=%q ' \
      "${REDUCED_ROTATION_PACKED_CHOLESKY_PROJECT}" \
      "${REDUCED_ROTATION_PACKED_TCG}" \
      "${REDUCED_ROTATION_PACKED_RIEMANNIAN_HVP}" \
      "${REDUCED_ROTATION_COMPACT_HVP}" \
      "${REDUCED_ROTATION_PRECOMPUTED_RESPONSE_HVP}"
    printf '%q ' "${cmd[@]}"
    printf '\n'
    printf '%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s\n' \
      "${dataset}" "${METHOD_NAME}" "dry_run" "${SCHEME}" "${LOCAL_SOLVER}" \
      "" "" "" "" "" "" "${result_path}" "${run_dir}" "${estimate_path}" "${iter_summary_path}" "${log_path}" >> "${SUMMARY_CSV}"
    return
  fi

  local start_ns end_ns
  local status=0
  start_ns="$(date +%s%N)"
  set +e
  DRAN_REDUCED_ROTATION_PACKED_CHOLESKY_PROJECT="${REDUCED_ROTATION_PACKED_CHOLESKY_PROJECT}" \
  DRAN_REDUCED_ROTATION_PACKED_TCG="${REDUCED_ROTATION_PACKED_TCG}" \
  DRAN_REDUCED_ROTATION_PACKED_RIEMANNIAN_HVP="${REDUCED_ROTATION_PACKED_RIEMANNIAN_HVP}" \
  DRAN_REDUCED_ROTATION_COMPACT_HVP="${REDUCED_ROTATION_COMPACT_HVP}" \
  DRAN_REDUCED_ROTATION_PRECOMPUTED_RESPONSE_HVP="${REDUCED_ROTATION_PRECOMPUTED_RESPONSE_HVP}" \
    "${cmd[@]}" 2>&1 | tee "${log_path}"
  status=${PIPESTATUS[0]}
  set -e
  end_ns="$(date +%s%N)"

  local final_objective=""
  local final_gradient=""
  local solver_time_per_node_sec=""
  local wall_time_sec=""
  local total_comm_poses=""
  local total_comm_mb=""

  final_objective="$(awk -F': *' '/^final objective:/ {value=$2} END {print value}' "${log_path}")"
  final_gradient="$(awk -F': *' '/^final gradient:/ {value=$2} END {print value}' "${log_path}")"
  solver_time_per_node_sec="$(awk '/^time:/ {value=$2} END {print value}' "${log_path}")"
  wall_time_sec="$(awk -v start="${start_ns}" -v end="${end_ns}" 'BEGIN {printf "%.9f", (end - start) / 1000000000.0}')"

  if [[ -f "${iter_summary_path}" ]]; then
    total_comm_poses="$(awk -F, 'NR > 1 {value=$7} END {print value}' "${iter_summary_path}")"
    total_comm_mb="$(awk -F, 'NR > 1 {value=$8} END {print value}' "${iter_summary_path}")"
  fi

  local status_text="ok"
  if [[ ${status} -ne 0 || -z "${final_objective}" || -z "${final_gradient}" ]]; then
    status_text="failed"
  fi

  printf '%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s\n' \
    "${dataset}" \
    "${METHOD_NAME}" \
    "${status_text}" \
    "${SCHEME}" \
    "${LOCAL_SOLVER}" \
    "${final_objective}" \
    "${final_gradient}" \
    "${total_comm_poses}" \
    "${total_comm_mb}" \
    "${solver_time_per_node_sec}" \
    "${wall_time_sec}" \
    "${result_path}" \
    "${run_dir}" \
    "${estimate_path}" \
    "${iter_summary_path}" \
    "${log_path}" >> "${SUMMARY_CSV}"
}

