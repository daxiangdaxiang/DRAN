dataset_suffix() {
  local scheme="$1"
  local accelerated="$2"
  scheme="$(sanitize "${scheme}")"
  accelerated="$(sanitize "${accelerated}")"
  if [[ "${scheme}" == "auto" ]]; then
    if [[ "${accelerated}" == "true" || "${accelerated}" == "1" || "${accelerated}" == "yes" || "${accelerated}" == "on" ]]; then
      printf '%s\n' "amm"
    else
      printf '%s\n' "mm"
    fi
  else
    printf '%s\n' "${scheme}"
  fi
}

