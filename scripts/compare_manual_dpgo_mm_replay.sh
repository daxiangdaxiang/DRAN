sanitize() {
  local value="$1"
  printf '%s' "${value}" | tr '[:upper:]' '[:lower:]'
}

csv_value() {
  local file="$1"
  local column="$2"
  awk -F, -v column="${column}" '
    NR == 1 {
      for (i = 1; i <= NF; ++i) {
        if ($i == column) {
          idx = i
        }
      }
    }
    NR == 2 && idx > 0 {
      print $idx
    }
  ' "${file}"
}

print_dry_run() {
