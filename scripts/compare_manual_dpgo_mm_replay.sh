  printf '%q ' "$@"
  printf '\n'
}

append_summary_row() {
  local dataset="$1"
  local updates="$2"
  local variant="$3"
  local run_root="$4"
  local summary="${run_root}/summary.csv"

  local status="missing_summary"
  local cost=""
  local gradient=""
  local comm_mb=""
  local wall_time=""
  local solver_time=""
  if [[ -f "${summary}" ]]; then
    status="$(csv_value "${summary}" "status")"
    cost="$(csv_value "${summary}" "global_cost")"
    gradient="$(csv_value "${summary}" "gradient")"
    comm_mb="$(csv_value "${summary}" "total_comm_mb")"
    wall_time="$(csv_value "${summary}" "wall_time_sec")"
    solver_time="$(csv_value "${summary}" "solver_time_per_node_sec")"
  fi

  printf '%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s\n' \
    "${dataset}" "${updates}" "${variant}" "${status}" "${cost}" \
    "${gradient}" "${comm_mb}" "${wall_time}" "${solver_time}" \
    "${run_root}" "${summary}" >> "${COMPARISON_CSV}"
}

write_pairwise_table() {
  {
    printf '%s\n' "dataset,updates,baseline,manual_cost,baseline_cost,manual_minus_baseline,manual_better"
    awk -F, '
    NR == 1 { next }
    {
      key = $1 "," $2
      cost[key "," $3] = $5
      status[key "," $3] = $4
    }
    END {
      for (key_variant in cost) {
        split(key_variant, parts, ",")
        dataset = parts[1]
        updates = parts[2]
        variant = parts[3]
        if (variant != "manual_reduced") {
          continue
        }
        key = dataset "," updates
        manual = cost[key ",manual_reduced"]
        for (baseline_idx = 1; baseline_idx <= 2; ++baseline_idx) {
          baseline = baseline_idx == 1 ? "dpgo_mm_mm" : "dpgo_mm_amm"
          base = cost[key "," baseline]
          if (manual == "" || base == "") {
            delta = ""
            better = "unknown"
          } else {
            delta = manual - base
            better = delta < 0 ? "true" : "false"
          }
          print dataset "," updates "," baseline "," manual "," base "," delta "," better
        }
      }
    }
    ' "${COMPARISON_CSV}" | sort
  } > "${PAIRWISE_CSV}"
}

